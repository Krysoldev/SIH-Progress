export function calculatePortfolioSummary(projects: Project[]): PortfolioSummary {
  const totalProjects = projects.length;
  const projectsAtRisk = projects.filter(p => p.status === 'AT RISK').length;
  const projectsCritical = projects.filter(p => p.status === 'CRITICAL').length;
  const projectsWatch = projects.filter(p => p.status === 'WATCH').length;
  const projectsOnTrack = projects.filter(p => p.status === 'ON TRACK').length;

  const totalPlannedCost = projects.reduce((acc, p) => acc + p.plannedCost, 0);
  const totalCurrentExpenditure = projects.reduce((acc, p) => acc + p.currentExpenditure, 0);

  const averageProgress = Math.round(
    projects.reduce((acc, p) => acc + p.physicalProgress, 0) / (totalProjects || 1)
  );

  const averageScheduleDelay = Number(
    (projects.reduce((acc, p) => acc + p.prediction.predictedTimeOverrun, 0) / (totalProjects || 1)).toFixed(1)
  );

  const forecastCostOverrun = Number(
    projects.reduce((acc, p) => acc + p.prediction.predictedCostOverrun, 0).toFixed(1)
  );

  const activeAlertsCount = projects.reduce(
    (acc, p) => acc + p.alerts.filter(a => a.status === 'ACTIVE').length,
    0
  );

  return {
    totalProjects,
    projectsAtRisk,
    projectsCritical,
    projectsWatch,
    projectsOnTrack,
    totalPlannedCost,
    totalCurrentExpenditure,
    averageProgress,
    averageScheduleDelay,
    forecastCostOverrun,
    activeAlertsCount,
  };
}
